#!/usr/bin/env python3
"""
Builds styles.css from styles.src.css, the pixel fonts and the contour picture, so the plugin
stays three files (main.js, manifest.json, styles.css).  Run:  python3 tools/build-css.py
"""
import base64
import pathlib
import urllib.parse

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'styles.src.css').read_text(encoding='utf8')


def font_face(family: str, file: str, weight: str) -> str:
    data = base64.b64encode((root / 'assets' / 'fonts' / file).read_bytes()).decode()
    return (
        "@font-face { font-family: '%s'; font-weight: %s; font-style: normal; font-display: swap;\n"
        "  src: url(data:font/woff2;base64,%s) format('woff2'); }\n" % (family, weight, data)
    )


fonts = (
    font_face('LRS Silkscreen', 'Silkscreen-Regular.woff2', '400')
    + font_face('LRS Silkscreen', 'Silkscreen-Bold.woff2', '700')
    + font_face('LRS Pixelify', 'PixelifySans.woff2', '400 700')
)

svg = (root / 'assets' / 'topo.svg').read_text(encoding='utf8').strip()
topo = ".lrs-party, .lrs-modalbox, .lrs-banner { --lrs-topo: url(\"data:image/svg+xml,%s\"); }\n" % urllib.parse.quote(svg, safe="/:=,;()' ")

header = (
    '/* Live Room Sync. Generated by tools/build-css.py from styles.src.css. Do not edit by hand.\n'
    ' * Fonts (embedded below), both under the SIL Open Font License 1.1, see licenses/ in the repository:\n'
    ' *   Silkscreen, Copyright 2001 The Silkscreen Project Authors (https://github.com/googlefonts/silkscreen)\n'
    ' *   Pixelify Sans, Copyright 2021 The Pixelify Sans Project Authors (https://github.com/eifetx/Pixelify-Sans)\n'
    ' */\n'
)
out = header + fonts + topo + src
(root / 'styles.css').write_text(out, encoding='utf8')
print('styles.css: %d bytes' % len(out.encode('utf8')))
